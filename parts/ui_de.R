tab_de <- function() {
  tabPanel("4. Differential analysis",
    tags$script(HTML("
      function contrastAct(i, a) { Shiny.setInputValue('c_action', {i: i, a: a, t: Date.now()}, {priority: 'event'}); }
      function contrastRename(el, i) { Shiny.setInputValue('c_rename', {i: i, name: el.innerText.trim(), t: Date.now()}, {priority: 'event'}); }")),
    sidebarLayout(
    sidebarPanel(width = 4, style = "max-height: 90vh; overflow-y: auto;",
      h4("Design"),
      uiOutput("de_covs_ui"),
      helpText("Model: ~ 0 + Group + covariates. Text columns are treated as factors,",
               "numeric columns as continuous."),
      h4("Contrasts"),
      h5("Compare two groups"),
      uiOutput("pair_builder"),
      textInput("cname", "Name (optional)", ""),
      fluidRow(
        column(6, actionButton("add_c", "Add contrast", class = "btn-primary")),
        column(6, actionButton("add_all", "Add all pairwise"))),
      br(),
      actionButton("adv_toggle", "Advanced options", icon = icon("cog"), class = "btn-link"),
      conditionalPanel("input.adv_toggle % 2 == 1",
        wellPanel(
          radioButtons("ctype", NULL,
                       c("Interaction (D - C) - (B - A)" = "inter",
                         "F-test over several contrasts" = "fsel",
                         "Custom expression" = "custom")),
          uiOutput("adv_builder"),
          textInput("cname_adv", "Name (optional)", ""),
          actionButton("add_adv", "Add contrast", class = "btn-primary"))),
      br(),
      hr(),
      h4("Technical replicates / repeated measures"),
      checkboxInput("de_block", "Samples include technical replicates of the same animal (duplicateCorrelation)", FALSE),
      conditionalPanel("input.de_block",
        radioButtons("block_src", "Identify the animal from",
                     c("A sample-info column" = "col",
                       "Regex removed from sample name" = "regex")),
        conditionalPanel("input.block_src == 'col'", uiOutput("block_col_ui")),
        conditionalPanel("input.block_src == 'regex'",
          textInput("block_regex", "Regex to strip (default removes trailing _<number>)", "_[0-9]+$")),
        verbatimTextOutput("block_preview")),
      checkboxInput("de_aw", "Estimate array weights (arrayWeights)", FALSE),
      hr(),
      h4("Test"),
      radioButtons("de_test", NULL, inline = TRUE,
                   c("eBayes" = "eBayes", "treat (min. fold change)" = "treat"), selected = "eBayes"),
      div(style = "display:flex; align-items:center; gap:10px; margin-bottom:8px;",
          tags$label("Fold change", style = "margin:0;"),
          numericInput("de_fc", NULL, 1.2, min = 1, step = 0.05, width = "80px"),
          tags$span(style = "color:#555;", textOutput("de_fc_pct", inline = TRUE))),
      checkboxInput("de_trend", "trend = TRUE", TRUE),
      checkboxInput("de_robust", "robust = TRUE", TRUE),
      h4("decideTests"),
      selectInput("dt_method", "Method", c("separate", "global", "hierarchical", "nestedF")),
      selectInput("dt_adjust", "P-value adjustment", c("BH", "BY", "holm", "bonferroni", "none")),
      numericInput("dt_p", "Adjusted p-value cutoff", 0.05, min = 0, max = 1, step = 0.01),
      br(),
      actionButton("run_de", "Run differential analysis", class = "btn-success btn-lg")
    ),
    mainPanel(
      uiOutput("pipeline_status_de"),
      tabsetPanel(id = "de_tabs",
        tabPanel("Design & contrasts", br(),
                 h4("Design"), verbatimTextOutput("design_txt"),
                 h4("Contrasts defined"), uiOutput("contrast_tbl")),
        tabPanel("Results", br(),
                 h4("Number of significant proteins"), uiOutput("de_summary"),
                 uiOutput("de_meta_txt"),
                 uiOutput("ftest_summary_ui"),
                 uiOutput("de_results_ui")),
        tabPanel("Subsets", br(),
          fluidRow(
            column(5, wellPanel(
      h4("A. Predefined subsets"),
      checkboxGroupInput("pre_method", NULL, inline = TRUE,
                   c("Per contrast (up/down)" = "contrast",
                     "Venn (unique / common / discordant)" = "venn"),
                   selected = c("contrast", "venn")),
      helpText("Both sets are created automatically after the analysis; use the button to regenerate."),
      numericInput("min_prot", "Minimum proteins per subset", 5, min = 1),
      actionButton("gen_pre", "Generate predefined subsets"),
      hr(),
      h4("B. Custom logic"),
      helpText("Choose a state per contrast, then how to combine them."),
      uiOutput("rules_ui"),
      radioButtons("rule_mode", NULL, inline = TRUE,
                   c("ALL rules (AND)" = "AND", "ANY rule (OR)" = "OR")),
      checkboxInput("rule_only", "ONLY: contrasts set to 'Ignore' must be non-significant", FALSE),
      textOutput("rule_count"),
      textInput("rule_name", "Name for this subset", ""),
      actionButton("add_custom", "Add to subset list")
            )),
            column(7,
              h4("Available subsets"), uiOutput("subset_tbl"),
              br(), downloadButton("dl_subsets", "Download all subsets (CSV)"))))
      )
    )
  ))
}
